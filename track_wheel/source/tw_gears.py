"""Hub-reduction gear profiles, generated the way they are cut.

The pinion is generated by an ISO 53 rack cutter (20 deg, addendum 1.0 m,
cutter addendum 1.25 m, tip radius 0.38 m). A standard 12-tooth pinion is
undercut, as a real hobbed gear would be. The ring is the envelope of that
pinion, rolled at the actual 7.0 mm gearbox shaft offset with a slightly larger
tip and with backlash, like a gear shaper cutting an internal gear. The pair is
therefore conjugate by construction at that centre distance.
Profiles are shapely polygons in mm, gear centre at the origin.
"""
import math
from functools import lru_cache
import numpy as np
from shapely.geometry import Polygon, Point, box
from shapely.affinity import rotate, translate
from shapely.ops import unary_union
from tw_design import GEAR_MODULE, PINION_TEETH, RING_TEETH, PRESSURE_ANGLE, CENTRE_DISTANCE, GEAR_BACKLASH, RING_BODY_R

M = GEAR_MODULE
ALPHA = math.radians(PRESSURE_ANGLE)


def rack_cutter(teeth=7, m=M, tip_round=.38, hf=1.0):
    """Cutter teeth point down (-y). Pitch line at y=0, tooth centred at x=0.

    hf is the cutter dedendum in modules: 1.0 for a normal gear, larger when
    generating a shaper cutter whose blank extends to 1.25 m.
    """
    p = math.pi * m; ha = 1.25 * m; hf = hf * m
    half_pitch_thick = p / 4                      # half cutter tooth thickness at the pitch line
    tip_half = half_pitch_thick - ha * math.tan(ALPHA)
    root_half = half_pitch_thick + hf * math.tan(ALPHA)
    shapes = []
    for k in range(-(teeth // 2), teeth // 2 + 1):
        x = k * p
        tooth = Polygon([(x - root_half, hf), (x - tip_half, -ha), (x + tip_half, -ha), (x + root_half, hf)])
        shapes.append(tooth)
    body = box(-(teeth // 2 + 1) * p, hf, (teeth // 2 + 1) * p, hf + 3 * m)
    cutter = unary_union(shapes + [body])
    # Rounded cutter tip (ISO 53 root fillet on the gear).
    r = tip_round * m
    return cutter.buffer(-r, join_style=1).buffer(r, join_style=1, quad_segs=6)


@lru_cache(maxsize=None)
def pinion_profile(z=PINION_TEETH, m=M, steps=241, addendum=1.0):
    """addendum=1.25 gives the matching shaper cutter (same base circle)."""
    rp = z * m / 2; ra = rp + addendum * m
    blank = Point(0, 0).buffer(ra, quad_segs=96)
    cutter = rack_cutter(m=m, hf=max(1.0, addendum + .2))
    cuts = []
    # Rack rolls on the pitch circle; in the gear frame it rotates by -phi.
    for phi in np.linspace(-math.radians(70), math.radians(70), steps):
        c = translate(cutter, xoff=-rp * phi, yoff=rp)
        cuts.append(rotate(c, -phi, origin=(0, 0), use_radians=True))
    cut = unary_union(cuts)
    one = blank.difference(cut)
    # Keep the tooth centred on +Y (between the cut spaces at +-180/z deg) and pattern it.
    pitch = 2 * math.pi / z
    wedge = Polygon([(0, 0)] + [(2 * ra * math.cos(math.pi / 2 + t), 2 * ra * math.sin(math.pi / 2 + t))
                                for t in np.linspace(-pitch / 2, pitch / 2, 9)])
    tooth = one.intersection(wedge)
    gear = unary_union([rotate(tooth, k * 360 / z, origin=(0, 0)) for k in range(z)])
    gear = orient(gear.buffer(.002).buffer(-.002))
    return gear.simplify(.002, preserve_topology=True)


def orient(shape):
    return shape if shape.geom_type == 'Polygon' else max(shape.geoms, key=lambda g: g.area)


@lru_cache(maxsize=None)
def ring_profile(zp=PINION_TEETH, zr=RING_TEETH, a=CENTRE_DISTANCE, m=M, backlash=GEAR_BACKLASH,
                 body_r=RING_BODY_R, steps_per_tooth=24):
    """Internal ring generated by the pinion acting as a shaper cutter.

    Ring frame fixed; the pinion centre travels on a circle of radius a while
    the pinion turns zr/zp times the ring angle in the same sense. The cutter is
    the pinion with its tip extended by 0.25 m (root clearance) and its flanks
    offset by half the normal backlash.
    """
    rp = zp * m / 2; rf = rp - 1.25 * m
    # Shaper cutter: same involute flanks, tip at 1.25 m, flanks offset by half the normal backlash.
    cutter = pinion_profile(zp, m, addendum=1.25).buffer(backlash * math.cos(ALPHA) / 2, quad_segs=4)
    cutter = cutter.simplify(.002, preserve_topology=True)
    r_tip = a + rf + .25 * m                       # ring tip circle clears the pinion root
    annulus = Point(0, 0).buffer(body_r, quad_segs=128).difference(Point(0, 0).buffer(r_tip, quad_segs=128))
    cuts = []
    n = zr * steps_per_tooth
    for k in range(n + 1):
        theta = 2 * math.pi * k / n               # ring-frame angle of the pinion centre
        # Pitch circle rolling inside the ring pitch circle (hypocycloid):
        # the pinion turns by -theta*(zr-zp)/zp while its centre advances theta.
        rel = theta * (1 - zr / zp)
        c = rotate(cutter, rel, origin=(0, 0), use_radians=True)
        c = translate(c, a * math.cos(theta), a * math.sin(theta))
        cuts.append(c)
    ring = annulus.difference(unary_union(cuts))
    return orient(ring.buffer(.002).buffer(-.002)).simplify(.002, preserve_topology=True)


def pinion_angle_for(ring_angle, zp=PINION_TEETH, zr=RING_TEETH):
    """Pinion self-rotation (deg) about its own axis, for a ring rotation (deg).

    Ring and pinion turn in the same sense; the pinion axis is fixed in the
    gearbox frame (shaft offset along +X in the ring generation frame at theta=0).
    """
    return ring_angle * zr / zp


def mesh_pose(ring_deg, a=CENTRE_DISTANCE):
    """Ring rotated by ring_deg, pinion at (a,0) rotated consistently."""
    ring = rotate(ring_profile(), ring_deg, origin=(0, 0))
    pin = rotate(pinion_profile(), pinion_angle_for(ring_deg), origin=(0, 0))
    return ring, translate(pin, a, 0)


def _overlap(ring, pin, a, phi_deg):
    return ring.intersection(translate(rotate(pin, phi_deg, origin=(0, 0)), a, 0)).area


def _contact_offset(ring, pin, a, phi0, sign, hi=6.0, tol=1e-5):
    """Pinion rotation offset (deg, signed) at which its flank first touches the ring."""
    lo, hi = 0.0, hi
    if _overlap(ring, pin, a, phi0) > 1e-9:
        return 0.0
    while hi - lo > tol:
        mid = (lo + hi) / 2
        if _overlap(ring, pin, a, phi0 + sign * mid) > 1e-7:
            hi = mid
        else:
            lo = mid
    return sign * (lo + hi) / 2


def mesh_check(a=CENTRE_DISTANCE, steps=36, eps=.005, zp=PINION_TEETH, zr=RING_TEETH):
    """Sweep one ring tooth pitch with the pinion at centre distance a.

    Returns the free pinion play (both flank contacts) as circumferential
    backlash on the pinion reference circle, the transmission error of the
    drive flank, and the mean number of tooth pairs within eps of contact
    (the numerical contact ratio).
    """
    ring = ring_profile(); pin = pinion_profile()
    rp = zp * M / 2
    pitch = 360.0 / zr
    rows = []
    for k in range(steps):
        beta = k * pitch / steps
        ring_b = rotate(ring, beta, origin=(0, 0))
        phi0 = beta * zr / zp
        clash = _overlap(ring_b, pin, a, phi0)
        dp = _contact_offset(ring_b, pin, a, phi0, +1)
        dm = _contact_offset(ring_b, pin, a, phi0, -1)
        # Teeth in contact when the drive flank is loaded.
        touching = translate(rotate(pin, phi0 + dp + 1e-4, origin=(0, 0)), a, 0).buffer(eps).intersection(ring_b)
        n = 0 if touching.is_empty else (len(touching.geoms) if hasattr(touching, 'geoms') else 1)
        rows.append(dict(beta=beta, clash_mm2=clash, plus_deg=dp, minus_deg=dm, contacts=n))
    play = [r['plus_deg'] - r['minus_deg'] for r in rows]
    to_mm = math.radians(1) * rp
    te = [r['plus_deg'] for r in rows]
    return dict(centre_distance=a, max_clash_mm2=max(r['clash_mm2'] for r in rows),
                backlash_min_mm=min(play) * to_mm, backlash_max_mm=max(play) * to_mm,
                transmission_error_pp_um=(max(te) - min(te)) * to_mm * 1000,
                contact_ratio=sum(r['contacts'] for r in rows) / steps,
                min_contacts=min(r['contacts'] for r in rows), rows=rows)


def pinion_form_radius(tol=.005, zp=PINION_TEETH, m=M):
    """Smallest radius from which the generated pinion flank is a true involute (within tol mm)."""
    pin = pinion_profile(); rp = zp * m / 2; rb = rp * math.cos(ALPHA)
    inv = lambda x: math.tan(x) - x
    pts = np.asarray(pin.exterior.coords)
    r = np.hypot(pts[:, 0], pts[:, 1]); th = np.arctan2(pts[:, 1], pts[:, 0])
    c = math.pi / 2 + math.pi / zp                    # a tooth centre (spaces at 90 deg + k pitch)
    rel = (th - c + math.pi) % (2 * math.pi) - math.pi
    sel = (np.abs(rel) < math.pi / zp) & (r >= rb) & (r < rp)
    half = lambda x: math.pi / (2 * zp) + inv(ALPHA) - inv(math.acos(rb / x))
    good = [x for x, t in zip(r[sel], np.abs(rel[sel])) if abs((t - half(x)) * x) < tol]
    return float(min(good)) if good else rp


def contact_ratio_theory(a=CENTRE_DISTANCE, zp=PINION_TEETH, zr=RING_TEETH, m=M, form_r='measured'):
    """Involute contact ratio of the internal pair at centre distance a.

    The ring tip circle (14.5) lies inside the ring base circle, so the ring
    flank is involute from its base circle; the path is limited by the pinion
    tip at one end and by the pinion form circle (undercut, measured on the
    generated profile) at the other. Distances s run along the line of action
    from the ring base-circle tangent point.
    """
    rb1 = zp * m / 2 * math.cos(ALPHA); rb2 = zr * m / 2 * math.cos(ALPHA)
    if form_r == 'measured':
        form_r = pinion_form_radius()
    alpha_w = math.acos((rb2 - rb1) / a)
    s1 = a * math.sin(alpha_w)                          # T2 -> T1 along the line of action
    ra1 = zp * m / 2 + m
    s_tip = s1 + math.sqrt(ra1 ** 2 - rb1 ** 2)          # pinion tip
    s_form = s1 + (math.sqrt(form_r ** 2 - rb1 ** 2) if form_r else 0.0)
    s_ring_root = math.sqrt((zr * m / 2 + 1.25 * m + (a - (zr - zp) * m / 2)) ** 2 - rb2 ** 2)
    length = min(s_tip, s_ring_root) - max(s_form, 0.0)
    return dict(working_pressure_angle_deg=math.degrees(alpha_w), pinion_form_radius_mm=form_r or rb1,
                path_start_mm=max(s_form, 0.0), path_end_mm=min(s_tip, s_ring_root),
                path_mm=length, contact_ratio=length / (math.pi * m * math.cos(ALPHA)))


def ring_tooth_thickness(radii, zr=RING_TEETH):
    """Arc thickness (mm) of the ring tooth centred on +X, at each radius."""
    from shapely.geometry import LineString
    ring = ring_profile()
    centre = 0.0                               # the pinion space faced +X when the ring was generated
    out = []
    for r in radii:
        arc = LineString([(r * math.cos(t), r * math.sin(t))
                          for t in np.linspace(centre - math.pi / zr, centre + math.pi / zr, 721)])
        piece = arc.intersection(ring)
        parts = list(piece.geoms) if hasattr(piece, 'geoms') else [piece]
        best = 0.0
        for p in parts:
            if p.length > 0 and p.distance(Point(r * math.cos(centre), r * math.sin(centre))) < 1e-6:
                best = p.length
        out.append(best)
    return out


def ring_lewis(torque_Nm, face=None, zr=RING_TEETH, m=M):
    """Ring tooth root bending stress (MPa) with the whole load on one tooth.

    The normal load T/rb acts tangentially at the innermost possible contact
    (the ring base circle); the critical chord is found by scanning sections
    between that point and the root. Conservative: no load sharing, no
    compressive relief.
    """
    from tw_design import PINION_FACE
    face = PINION_FACE if face is None else face
    rb = zr * m / 2 * math.cos(ALPHA)
    fn = torque_Nm / (rb / 1000)
    radii = np.linspace(rb + .05, 17.85, 60)
    s = ring_tooth_thickness(radii)
    best = max((6 * fn * (r - rb) / (face * t ** 2), r, t) for r, t in zip(radii, s) if t > 0)
    return dict(stress_MPa=best[0], critical_radius_mm=best[1], critical_chord_mm=best[2],
                normal_load_N=fn, load_radius_mm=rb, face_mm=face)


def contact_stress(torque_Nm, a=CENTRE_DISTANCE, zp=PINION_TEETH, zr=RING_TEETH, m=M,
                   e_plastic=2000., nu_plastic=.38, e_steel=210000., nu_steel=.3):
    """Hertz line-contact pressure (MPa) at the operating pitch point, one tooth pair."""
    from tw_design import PINION_FACE
    rb1 = zp * m / 2 * math.cos(ALPHA); rb2 = zr * m / 2 * math.cos(ALPHA)
    aw = math.acos((rb2 - rb1) / a)
    r1 = a * zp / (zr - zp); r2 = a * zr / (zr - zp)
    rho = 1 / (1 / (r1 * math.sin(aw)) - 1 / (r2 * math.sin(aw)))
    e_star = 1 / ((1 - nu_plastic ** 2) / e_plastic + (1 - nu_steel ** 2) / e_steel)
    fn = torque_Nm / (rb2 / 1000)
    return dict(pressure_MPa=math.sqrt(fn * e_star / (math.pi * PINION_FACE * rho)), equivalent_radius_mm=rho,
                operating_pitch_radii_mm=[r1, r2], normal_load_N=fn)
