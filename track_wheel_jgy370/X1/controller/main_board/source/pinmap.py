"""Firmware pin map of the X1 main board, from netlist.py.

Writes PINMAP.md (for people) and x1_main_pins.h (for the firmware), so the firmware cannot drift
from the board. The header is also written, byte for byte, into the machine sketch
(../firmware/x1_main/src/), because the Arduino build copies the sketch folder and cannot reach
files outside it. firmware/test/run_tests.sh checks that the two copies are identical.

    python pinmap.py
"""
from pathlib import Path

import calcs as CA
import netlist as NL

BOARD = Path(__file__).resolve().parent.parent
SKETCH_PINS = BOARD.parent / "firmware" / "x1_main" / "src" / "x1_main_pins.h"

GPIO_OF = {net: g for g, net in NL.GPIO_MISC.items()}
MISC_NOTE = {
    "VBAT_SNS": (f"ADC1_CH{GPIO_OF['VBAT_SNS'] - 1}", "battery voltage x 22k/122k"),
    "BUZ_PWM": ("LEDC", "buzzer, PWM at about 2.7 kHz"),
    "NSLEEP": ("output", "all seven drivers: 1 = awake (armed), 0 = sleep; 100k pull-down"),
    "NFAULT": ("input", "any driver fault, open drain, 10k pull-up; low = fault"),
    "LED_STAT": ("output", "status LED, high = on"),
    "EXP_TX": ("UART1 TX", "expansion header pin 3 (through 100R)"),
    "EXP_RX": ("UART1 RX", "expansion header pin 4 (through 1k)"),
    "LAMP1_PWM": ("LEDC", "lamp 1 low-side switch; strap pin, 100k pull-down"),
    "LAMP2_PWM": ("LEDC", "lamp 2 low-side switch; strap pin, 100k pull-down"),
    "BOOT": ("input", "BOOT button (strap); usable as a user button after boot"),
    "USB_DN": ("USB", "native USB D-"),
    "USB_DP": ("USB", "native USB D+"),
    "TXD0": ("UART0 TX", "boot log, test pad TP201"),
    "RXD0": ("UART0 RX", "test pad TP202"),
}


def rows():
    out = []
    for ch in NL.CHANNELS:
        k, it = ch["key"], CA.itrip(ch)
        out.append((ch["en"], f"EN_{k}", "PWM (MCPWM)", f"{ch['name']}: speed, 0 = brake"))
        out.append((ch["ph"], f"PH_{k}", "output", f"{ch['name']}: direction, 1 = OUT1 high"))
        out.append((ch["adc"], f"ISNS_{k}", f"ADC1_CH{ch['adc'] - 1}",
                    f"{ch['name']}: current, {ch['r_ipropi']:g} ohm x 1000 uA/A; {it:.3f} A limit = {CA.vref():.3f} V"))
    for g, net in NL.GPIO_MISC.items():
        per, note = MISC_NOTE[net]
        out.append((g, net, per, note))
    return sorted(out)


def main():
    r = rows()
    md = [f"# X1 main board rev {NL.REV}: firmware pin map", "",
          "Generated by `source/pinmap.py` from `source/netlist.py`; do not edit by hand. The firmware includes "
          "`x1_main_pins.h` from the same source.", "",
          f"{len(r)} of the 36 GPIO of the ESP32-S3-WROOM-1-N8 are assigned; GPIO7 is free (revision A sensed "
          f"the 6 V actuator rail there). Analog inputs use ADC1 at 12 dB (0-2.9 V). VREF = {CA.vref():.3f} V.", "",
          "| GPIO | Net | Function | Use |", "|---|---|---|---|"]
    md += [f"| {g} | `{n}` | {p} | {u} |" for g, n, p, u in r]
    (BOARD / "PINMAP.md").write_text("\n".join(md) + "\n")
    h = ["// X1 main board rev " + NL.REV + ": GPIO map. Generated by main_board/source/pinmap.py from netlist.py;",
         "// do not edit by hand.", "#pragma once", "", "namespace x1pins {", ""]
    for g, n, p, u in r:
        h.append(f"constexpr int {n} = {g};  // {p}: {u}")
    h += ["", "struct Channel { const char *name; int en, ph, isns; float r_ipropi_ohm; float limit_a; };",
          "constexpr Channel CHANNELS[] = {"]
    for ch in NL.CHANNELS:
        h.append(f"    {{\"{ch['name']}\", {ch['en']}, {ch['ph']}, {ch['adc']}, {ch['r_ipropi']:.1f}f, "
                 f"{CA.itrip(ch):.4f}f}},")
    h += ["};", f"constexpr float VREF_V = {CA.vref():.4f}f;",
          f"constexpr float VBAT_DIVIDER = {CA.divider('R102', 'R103'):.5f}f;  // V_adc = VBAT x this",
          "", "}  // namespace x1pins", ""]
    header = "\n".join(h)
    (BOARD / "x1_main_pins.h").write_text(header)
    SKETCH_PINS.parent.mkdir(parents=True, exist_ok=True)
    SKETCH_PINS.write_text(header)
    print(f"{len(r)} GPIO rows")


if __name__ == "__main__":
    main()
