"""Bill of materials for the X1 main board, from netlist.py.

Writes fab/X1_main_board_<rev>_BOM_JLCPCB.csv (JLCPCB assembly format) and BOM.md (grouped, with the
JLCPCB library type, which decides the per-part loading fee). Test pads and holes are copper only.

    python bom.py
"""
import csv
from collections import OrderedDict
from pathlib import Path

import netlist as NL

BOARD = Path(__file__).resolve().parent.parent
STEM = f"X1_main_board_{NL.REV}"
# JLCPCB library type as listed on 2026-11-05 (PARTS_SOURCES in DESIGN.md); anything else is Extended
BASIC = {"C8598", "C318884", "C2286", "C2297", "C14663", "C21122", "C15849", "C15850", "C12891", "C25804", "C25803",
         "C21190", "C23046", "C22775", "C23186", "C31850", "C21189", "C22940", "C22978"}
PREFERRED = {"C28262", "C25950"}


def lib_type(lcsc):
    return "Basic" if lcsc in BASIC else "Preferred ext." if lcsc in PREFERRED else "Extended"


def natural(ref):
    head = ref.rstrip("0123456789")
    return head, int(ref[len(head):] or 0)


def lines():
    nl = NL.build()
    groups = OrderedDict()
    for ref, p in nl.parts.items():
        info = nl.info(ref)
        if not info.get("lcsc") or p["dnp"]:
            continue
        key = (info["lcsc"], info["value"], info["footprint"])
        groups.setdefault(key, dict(info=info, refs=[]))["refs"].append(ref)
    out = []
    for (lcsc, value, fp), g in groups.items():
        refs = sorted(g["refs"], key=natural)
        out.append(dict(refs=refs, qty=len(refs), value=value, mpn=g["info"]["mpn"], footprint=fp, lcsc=lcsc,
                        lib=lib_type(lcsc), height=g["info"]["height"]))
    out.sort(key=lambda r: natural(r["refs"][0]))
    return out


def main():
    rows = lines()
    (BOARD / "fab").mkdir(exist_ok=True)
    with open(BOARD / "fab" / f"{STEM}_BOM_JLCPCB.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Comment", "Designator", "Footprint", "LCSC Part #"])
        for r in rows:
            w.writerow([f"{r['value']} {r['mpn']}", ",".join(r["refs"]), r["footprint"].split(":")[1], r["lcsc"]])
    n_parts = sum(r["qty"] for r in rows)
    ext = [r for r in rows if r["lib"] == "Extended"]
    md = [f"# X1 main board rev {NL.REV}: bill of materials",
          "",
          "Generated by `source/bom.py` from `source/netlist.py`; do not edit by hand.",
          "",
          f"- {len(rows)} lines and {n_parts} placed parts per board. Test pads and mounting holes are copper only.",
          f"- **JLCPCB library type:** {sum(1 for r in rows if r['lib'] == 'Basic')} lines are Basic, "
          f"{sum(1 for r in rows if r['lib'] == 'Preferred ext.')} are Preferred Extended, and {len(ext)} are "
          "Extended, which carry a per-part loading fee.",
          "- The library type, part numbers and ratings were checked on LCSC and JLCPCB on 2026-11-05 "
          "(sources in DESIGN.md).",
          "",
          "| Designators | Qty | Value | Part | Footprint | LCSC | JLC library | Height mm |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {', '.join(r['refs'])} | {r['qty']} | {r['value']} | {r['mpn']} | "
                  f"`{r['footprint'].split(':')[1]}` | {r['lcsc']} | {r['lib']} | {r['height']:g} |")
    (BOARD / "BOM.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} BOM lines, {n_parts} parts, {len(ext)} Extended lines")


if __name__ == "__main__":
    main()
