def mesh(shape, tol=.05, ang=.3):
    v, t = shape.val().tessellate(tol, ang)
    return np.array([[p.x, p.y, p.z] for p in v], float), np.array(t, int)


def free_connectors():
    """(name, shape, colour, mover, joint id) of the connectors drawn here, mated, in the vehicle frame."""
    out = []
    j101 = next(j for j in C.JOINTS if j['id'] == 'J101')
    # the XT30U-F of the 12 V link: the board's XT30PW-M is the male with its mouth at x = -40.54 facing +X, so the mated
    # frame (male mouth at x = 0, female at +X) maps straight onto the vehicle frame
    for n, s, c in SP.place(SP.xt30u_f(wire_len=4.0), j101['pos']):
        out.append((f'board_link_XT30U-F_{n}', s, c, 'upper', 'J101'))
    # SM pairs: the mated frame has the receptacle mouth at x = 0, its body at -X and the plug at +X (plug wires at +X)
    for j, plug_dir in (('SM-L', (0, 1, 0)), ('SM-R', (0, -1, 0)), ('SM-LAMP', (1, 0, 0))):     # plug side (wires) direction; receptacle at the other side
        jt = next(x for x in C.JOINTS if x['id'] == j)
        mover = 'ground' if j != 'SM-LAMP' else 'upper'
        rot = [C.rot_to((1, 0, 0), plug_dir)]
        zc = SP.SM['r_h'] / 2                                 # centre the pair's height on the joint position
        for n, s, c in SP.place(SP.sm_receptacle(2, wire_len=4.0), (0, 0, -zc), rot=rot):
            out.append((f'{j}_SMR-02V-B_{n}', s.translate(jt['pos']), c, mover, j))
        for n, s, c in SP.place(SP.sm_plug(2, wire_len=4.0), (0, 0, -zc), rot=rot):
            out.append((f'{j}_SMP-02V-BC_{n}', s.translate(jt['pos']), c, mover, j))
    return out


def write_meshes():
    parts = []
    for name, s, c, mover, j in free_connectors():
        v, t = mesh(s)
        parts.append(dict(name=name, v=v.round(4).tolist(), t=t.tolist(), color=list(c), mover=mover, joint=j, kind='connector'))
    K.save_gz(OUT_MESH, dict(parts=parts, note='build_connectors.py: mated free connectors of the harness, vehicle frame, swing 0'))
    print('meshes', len(parts), '->', OUT_MESH.name)


def write_steps():
    STEP_DIR.mkdir(parents=True, exist_ok=True)
    pairs = {'XT30U-F_and_XT30U-M_mated': SP.xt30u_f() + [('m_' + n, s, c) for n, s, c in SP.xt30u_m()],
             'SMR-02V-B_and_SMP-02V-BC_mated': SP.sm_receptacle() + [('p_' + n, s, c) for n, s, c in SP.sm_plug()],
             'Keystone_1043_with_INR18650-35E': SP.keystone_1043() + [('cell_' + n, s, c) for n, s, c in
                                                                     SP.place(SP.cell_18650(), (0, SP.K1043['cell_y'], SP.K1043['base'] + SP.K1043['cell_d'] / 2 + .15))]}
    for name, fn in list(SP.ALL.items()) + [(k, (lambda v=v: v)) for k, v in pairs.items()]:
        asm = cq.Assembly(name=name)
        for n, s, c in fn():
            asm.add(s, name=n, color=cq.Color(*c))
        asm.save(str(STEP_DIR / f'{name}.step'), exportType='STEP')
    print('STEP files', len(SP.ALL) + len(pairs), '->', STEP_DIR)


