def classify(name):
    """Category and designation of a bought part from its name in the subsystem scenes."""
    n = name
    if n.startswith('RU66'):
        return 'bearing', 'THK RU66 cross-roller ring (Ø35 bore, Ø95, 15 high)'
    for code, des in (('624ZZ', '624ZZ 4 x 13 x 5 (two per roller)'), ('608ZZ', '608ZZ 8 x 22 x 7 (idler)'), ('6800ZZ', '6800ZZ 10 x 19 x 5 (sprocket journal)')):
        if n.startswith(code):
            return 'bearing', des
    if n.startswith('Pololu_1999'):
        return 'hub', 'Pololu #1999 6 mm universal hub (swing pinion to the motor shaft)'
    if n.startswith('flange_coupling'):
        return 'hub', 'Ø32 / Ø6 flange coupling (sprocket to the motor shaft)'
    if n.startswith('nyloc'):
        return 'fastener', 'M4 nyloc nut (roller axle)'
    if n.startswith('drag_felt'):
        return 'other', 'felt drag pad'
    if n.startswith('collar '):
        return 'collar', 'shaft collar with set screw on pin ' + n.split(' ')[1] + (' (Ø6)' if n.split(' ')[1] in ('O', 'E', 'H') else ' (Ø3)')
    if n == 'ballast_steel_shot':
        return 'other', 'steel shot ballast (counterweight pocket)'
    if n.startswith('slip_ring'):
        return 'slip ring', '6-way 2 A flanged slip ring (Ø22 body, Ø44 flange)'
    if n.startswith('JGY370'):
        return 'motor', 'JGY-370 worm-gear motor (12 V)'
    if 'magnet' in n:
        return 'magnet', 'NdFeB disc Ø6 x 2 (N42/N52)'
    if 'insert' in n:
        size = 'M6' if 'M6' in n else 'M4' if 'M4' in n else 'M3'
        return 'insert', f'{size} heat-set insert'
    if 'spring' in n:
        return 'spring', 'disc spring DIN 6796 M4' if 'disc' in n else 'recoil spring' if 'recoil' in n else 'drag-pad spring'
    if n.startswith('pin_') or 'idler_pin' in n or 'axle' in n:
        return 'pin', 'steel pin ' + n.split('_d')[-1].replace('x', ' x ') if '_d' in n else 'steel pin / axle'
    if 'bushing' in n or 'bush' in n:
        return 'bushing', 'steel bushing'
    if 'screw' in n or 'bolt' in n or 'nut' in n or 'washer' in n:
        return 'fastener', n.replace('_', ' ')
    if n.startswith(('cell_18650',)):
        return 'cell', 'Samsung INR18650-35E'
    if n.startswith('holder_1043'):
        return 'battery holder', 'Keystone 1043'
    if n.startswith('battery_BMS'):
        return 'BMS', 'HX-3S-01 3S 10 A'
    if n == 'board_plugs':
        return 'connector', '7 mated JST plugs: 5 x XHP-2, XHP-4, PHR-3 (CONNECTORS.md J102-J108)'
    if n.startswith('battery_lead_XT30'):
        return 'connector', 'Amass XT30U-F on the hatch lead (CONNECTORS.md FEED)'
    if n.startswith('feed_socket'):
        return 'connector', 'Amass XT30U-M on the feed (CONNECTORS.md FEED)'
    if n.startswith('board_link'):
        return 'connector', 'Amass XT30U-F of the 12 V link on the board\'s XT30PW-M (CONNECTORS.md J101)'
    if n.startswith('SM-'):
        j, model = n.split('_')[0], n.split('_')[1]
        return 'connector', f'JST {model} ({"pins, stator / board side" if model.startswith("SMR") else "sockets, motor / lamp side"}; CONNECTORS.md {j})'
    if n.startswith(('board_plugs', 'board_parts_jst', 'board_parts_xt30', 'board_parts_usb')):
        return 'connector', 'see CONNECTORS.md'
    if n.startswith(('controller_PCB', 'board_parts')):
        return 'board', 'X1 main board rev B (ESP32-S3-WROOM-1, 7 x DRV8876, JST headers, XT30PW-M, USB-C)'
    if n.startswith(('main_switch',)):
        return 'connector', 'KCD1-101 rocker switch'
    if n.startswith('charge_jack'):
        return 'connector', '5.5 x 2.1 panel jack (DC-022B)'
    if n.startswith('fuse_holder'):
        return 'connector', 'Littelfuse MINI FHM holder + 5 A'
    return 'other', n.replace('_', ' ')


def standard_parts(parts, cfg):
    """Markers: every bought part's centre, category and designation, for both tracks (the J9 scene is drawn twice)."""
    rows = []
    names = sorted({p['name'] for p in parts}, key=len)
    def stem(n):                                                   # the bought part a piece belongs to ('holder_1043_0' for 'holder_1043_0_contacts')
        return next((m for m in names if n == m or n.startswith(m + '_')), n)
    for p in parts:
        if p['kind'] in ('printed', 'drive') or p['name'].startswith(('reserved', 'spacer ')):   # V6 bodies and the R12 pin spacers are prints
            continue
        if stem(p['name']) != p['name'] or p['name'].startswith('board_parts'):              # one marker per bought part, not per piece; the board is one part
            continue
        if p['kind'] == 'connector' and not p['name'].endswith('_housing'):                    # the free connectors: one marker per housing
            continue
        cat, des = classify(p['name'])
        c = p['v'].mean(axis=0)
        sides = [p['side']] if p['mover'] == 'track' else [0]
        for sd in sides:
            pos = c.copy()
            if sd:                                                # machine.track_frame: the right module is the left one mirrored in Y
                pos = np.array([c[0], sd * (cfg['track_y'] + c[1]), c[2]])
            rows.append(dict(name=p['name'].replace('_housing', '') + (f' ({"left" if sd > 0 else "right"} track)' if sd else ''), cat=cat, des=des, sys=p['sys'],
                             mover=p['mover'] if not sd else 'track', side=sd, pos=[round(float(v), 1) for v in pos], source=p.get('part') or p['sys']))
    # one marker per bearing (the J9 scene draws each as inner ring, outer ring and shield: keep the outer ring's)
    rows = [r for r in rows if not (r['cat'] == 'bearing' and r['name'].split(' (')[0].endswith(('_inner', '_shield')))]
    for r in rows:
        if r['cat'] == 'bearing' and '_outer' in r['name']:
            r['name'] = r['name'].replace('_outer', '')
    return rows


def write_standard_parts(rows):
    cats = {}
    for r in rows:
        cats.setdefault(r['cat'], []).append(r)
    order = ['bearing', 'slip ring', 'motor', 'hub', 'magnet', 'insert', 'spring', 'pin', 'collar', 'bushing', 'cell', 'battery holder', 'BMS', 'board', 'connector', 'fastener', 'other']
    md = ['# Standard (bought) parts of the complete X1 excavator and where they sit', '',
          'Every place that takes a bought standard component: bearings and the slewing ring, the slip ring, motors, magnets, heat-set inserts, springs, pins, the '
          'battery pack and the connectors, and the fasteners. Positions are centres in the vehicle frame at swing 0 (mm; X forward, Y left, Z up). The same '
          'markers are drawn in `3D_preview.html` ("Standard parts" in the layer list: click a marker to read it). Generated by `source/build_connectors.py` from the '
          'subsystem scenes and the J9 configuration; the purchase specifications are in [BOM.md](BOM.md) and the connector models in [CONNECTORS.md](CONNECTORS.md).', '']
    md += ['| Category | Count |', '|---|---|'] + [f'| {c} | {len(cats[c])} |' for c in order if c in cats] + ['']
    for c in order:
        if c not in cats:
            continue
        md += [f'## {c.capitalize()} ({len(cats[c])})', '', '| Part | Designation | Subsystem | Position X, Y, Z |', '|---|---|---|---|']
        for r in sorted(cats[c], key=lambda r: (r['sys'], r['name'])):
            md.append(f"| {r['name'].replace('_', ' ')} | {r['des']} | {r['sys']} | {r['pos'][0]}, {r['pos'][1]}, {r['pos'][2]} |")
        md.append('')
    (K.ROOT / 'STANDARD_PARTS.md').write_text('\n'.join(md))
    print('STANDARD_PARTS.md:', {c: len(v) for c, v in cats.items()})


