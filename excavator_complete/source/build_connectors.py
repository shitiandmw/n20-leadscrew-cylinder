"""Connector models, catalogue and standard-parts list of the complete X1 excavator.

Writes
  ../cad/connectors_mesh.json.gz   the free connectors that no subsystem CAD draws: the XT30U-F of the 12 V link on the board's
                                   XT30PW-M, and the three JST SM wire-to-wire pairs (two in the carbody, one at the body seam),
                                   as viewer meshes in the vehicle frame (machine.py adds them to the harness layer)
  ../step/connectors/<model>.step  one coloured STEP per connector / battery-pack model (stdparts.py), for inspection
  ../CONNECTORS.md, ../connectors.csv   every connector: type, model, mate, contacts, wire, location, fitting step (connectors.py)
  ../STANDARD_PARTS.md             every bought standard part with where it sits (bearings, rings, motors, magnets, inserts,
                                   fasteners, connectors, cells), from the machine's part list and the J9 configuration
Run with the R12 interpreter from this folder (needs cadquery; stdparts.py is imported from track_wheel_jgy370/X1/source).
"""
